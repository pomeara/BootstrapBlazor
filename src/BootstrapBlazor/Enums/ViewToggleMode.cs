namespace BootstrapBlazor.Components;

/// <summary>
/// View toggle display mode.
/// </summary>
public enum ViewToggleMode
{
    /// <summary>
    /// Two visible buttons, one per view.
    /// </summary>
    DualButton,

    /// <summary>
    /// A single button that toggles between the two views.
    /// </summary>
    SingleButton
}
